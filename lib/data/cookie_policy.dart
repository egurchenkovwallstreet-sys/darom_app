4. Что хранится в localStorage браузера

На вашем устройстве локально могут сохраняться:

• номер телефона и отображаемое имя — для отображения профиля без повторного ввода;
• идентификатор пользователя в Сервисе;
• служебные флаги режима сессии (например, что вход выполнен через защищённую cookie);
