2. Что такое cookie и localStorage

• **Cookie (куки)** — небольшой файл, который браузер сохраняет на вашем устройстве. Сайт может читать его при следующих визитах.
• **localStorage** — встроенное хранилище браузера для данных сайта (не отправляется автоматически на другие сайты).

